// 소수 첫째 자리 반올림
function r1(x) { return Math.round(x * 10) / 10; }

// 가격 변동 적용: 현재가 × (1 + %/100), 소수 첫째 자리 반올림
function applyDeltas(prices, deltas) {
  const out = {};
  for (const id of STOCK_IDS) {
    const d = (deltas && deltas[id]) || 0;
    out[id] = Math.max(0.1, r1(prices[id] * (1 + d / 100)));
  }
  return out;
}

function initialPrices() {
  const p = {};
  for (const id of STOCK_IDS) p[id] = GAME.startPrice;
  return p;
}

function emptyHoldings() {
  const h = {};
  for (const id of STOCK_IDS) h[id] = 0;
  return h;
}

// 총자산 = 현금 + Σ(보유주 × 현재가)
function calcAsset(cash, holdings, prices) {
  let a = cash || 0;
  for (const id of STOCK_IDS) a += ((holdings && holdings[id]) || 0) * prices[id];
  return r1(a);
}

// 라운드별 뉴스 3장의 표시 순서 (결정적 셔플 — 모든 기기에서 동일)
// 반환: ["d1","real","d2"] 같은 배열
function cardOrder(round) {
  const arr = ["real", "d1", "d2"];
  let s = round * 7919 + 104729;
  for (let i = arr.length - 1; i > 0; i--) {
    s = (s * 9301 + 49297) % 233280;
    const j = Math.floor((s / 233280) * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

// 카드 키("real"|"d1"|"d2") → 카드 데이터
function getCard(round, key) {
  const R = ROUNDS[round - 1];
  if (key === "real") return { key, title: R.real.title, body: R.real.body, isReal: true };
  const d = R.dummies[key === "d1" ? 0 : 1];
  return { key, title: d.title, body: d.body, whyNo: d.whyNo, isReal: false };
}

// 라운드의 표시 순서대로 카드 3장 반환
function roundCards(round) {
  return cardOrder(round).map(k => getCard(round, k));
}

